import type { EmotionKey } from "./types";

/**
 * 「AI 情绪分析」的 Mock 实现（服务端）。
 *
 * 设计：根据用户在「今天发生了什么？」里写下的文字，识别对应情绪。
 * 当前为关键词规则匹配；后端接入真实 LLM 时，可替换本函数的实现，
 * 契约保持不变（输入文字，输出 EmotionKey）。
 *
 * 注意：情绪没有「好坏」，只是如实识别文字里透露出的感受。
 */
const RULES: [string[], EmotionKey][] = [
  [["难过", "哭", "失落", "低落", "想放弃", "不值得", "绝望", "悲伤", "心痛", "心碎", "郁闷", "否定", "被否"], "sad"],
  [["生气", "愤怒", "气死", "烦", "不公平", "推卸", "委屈", "凭什么", "恼", "火大", "生气了"], "angry"],
  [["焦虑", "担心", "害怕", "紧张", "睡不着", "反复", "预演", "最坏", "不安", "恐慌", "压力", "汇报"], "anxious"],
  [["累", "疲惫", "掏空", "加班", "没力气", "撑不住", "倦", "耗尽", "透支"], "tired"],
  [["迷茫", "看不清", "不知道怎么办", "方向", "困惑", "摸不清", "乱"], "confused"],
  [["开心", "高兴", "愉快", "笑", "快乐", "不错"], "happy"],
  [["兴奋", "激动", "雀跃", "期待"], "excited"],
  [["感动", "触动", "暖", "眼眶", "泪目", "破防"], "moved"],
  [["希望", "盼", "向往", "期待光", "心里有光"], "hopeful"],
  [["感谢", "感激", "谢谢", "感恩"], "grateful"],
  [["满足", "踏实", "够了", "安心", "松弛"], "content"],
];

/** 从文字识别情绪；匹配不到时默认 calm（平静）。 */
export function analyzeEmotion(text: string): EmotionKey {
  const t = (text || "").toLowerCase();
  for (const [keywords, emotion] of RULES) {
    if (keywords.some((k) => t.includes(k.toLowerCase()))) return emotion;
  }
  return "calm";
}
